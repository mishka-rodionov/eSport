package com.competra.domain.models.diary

/** Статус тренировки в дневнике. */
enum class WorkoutStatus {
    /** Запланирована на будущую дату, ещё не выполнена. */
    PLANNED,

    /**
     * Live-трекинг активен прямо сейчас. Выставляется и снимается только сервисом трекинга —
     * никогда не выбирается вручную в редакторе. Исключена из выгрузки на сервер, пока не
     * перейдёт в [COMPLETED] (см. `WorkoutDao.getUnsynced()`).
     */
    IN_PROGRESS,

    /** Выполнена (записана постфактум вручную или завершённым live-трекингом). */
    COMPLETED
}
